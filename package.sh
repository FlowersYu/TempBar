#!/bin/zsh
# package.sh — 生成可分发给同事的 zip 包
set -e
cd "$(dirname "$0")"
ROOT="$(pwd)"
DIST="$ROOT/dist"
APP="$ROOT/build/TempBar.app"

[ -d "$APP" ] || { echo "先跑 ./build.sh"; exit 1; }

rm -rf "$DIST"
mkdir -p "$DIST"

echo "==> 打包 TempBar.zip"
# 用 ditto 而不是 zip：能保住 .app 的符号链接、权限和扩展属性，
# 用普通 zip 解压出来的 app 经常因为丢权限而打不开
ditto -c -k --sequesterRsrc --keepParent "$APP" "$DIST/TempBar.zip"

cat > "$DIST/安装说明.txt" <<'TXT'
TempBar —— 温度计桌面小组件
==============================

一、安装
  1. 双击 TempBar.zip，解压出 TempBar.app
  2. 把 TempBar.app 拖到「应用程序」文件夹
  3. 第一次打开：右键点 TempBar.app → 选「打开」→ 再点「打开」
     （必须走这一步。因为没用付费证书公证，直接双击会被系统拦住）
  4. 系统会问「TempBar 想使用蓝牙」→ 点「允许」
     不允许的话收不到任何数据

二、用法
  - 菜单栏右上角出现温度，比如 23.5°
  - 左键点它 → 看详情（曲线、电量、信号）
  - 右键点它 → 开关桌面小组件、进设置、退出
  - 桌面小组件可以随便拖到你喜欢的位置，位置会被记住
  - 右键点小组件 → 尺寸（小/中/大）、主题（经典/仿苹果）、
    设为浮动置顶、隐藏
  - 菜单面板固定浅色显示，不会跟着系统深浅色切换而跳色

三、给温度计改名
  温度计广播的原始名字通常是一串编号，比如 ATC_F871A7。
  想把它改成「办公室温湿度计」这种：
    右键点小组件 → 重命名设备… → 在「显示名称」里输入 → 回车
  也可以用菜单栏图标 → 设置… → 设备 → 显示名称。

  - 名字只存在你这台电脑上，不影响温度计本身，也不影响别人
  - 旁边有「恢复」按钮，一键退回原始名称
  - 框里留空也等于恢复原名
  - 接多台温度计时，先在「当前设备」下拉里选一台，再改名

四、收不到数据怎么办
  1. 确认温度计在 10 米以内，中间最好别隔承重墙
  2. 确认系统蓝牙是开着的
  3. 打开设置 → 诊断 → 点「复制设备列表」，看能不能列出设备
  4. 检查温度计固件：广播格式要是 BTHome v2，且不要开加密
  5. 检查固件里有没有勾选「温度」「湿度」——只勾电压的话，
     能扫到设备但不会显示温度（这是最常见的原因）
  6. 电池电压低于 2.6V 会导致广播变弱

五、尺寸与主题
  尺寸和主题是两件独立的事，可以任意组合，一共 6 种。都按 Apple
  官方 HIG 的组件规范做，圆角和留白是量着调的：

    尺寸
      小号  158×158   名称 + 大温度 + 湿度 + 当天最高/最低（全部居中）
      中号  338×158   经典主题：右边多一条近 6 小时曲线
                      仿苹果主题：右侧竖排当天最高/最低
      大号  338×354   经典主题：大读数 + 当天最高最低 + 近 24 小时曲线
                      仿苹果主题：仿苹果天气组件的整套排版（左对齐）

    主题
      经典      浅色卡片，跟随系统深浅色切换
      仿苹果    深靛蓝到紫蓝的渐变、白色细体大字，
                不跟随系统深浅色 —— 苹果那个组件本身就是这样，
                配色算内容的一部分，不是外观的一部分

  可以来回切换，切完窗口会保持左上角位置不动。
  改主题不会改尺寸，改尺寸也不会把主题切回去。

  最高/最低算的是"今天已经测到的"，不是天气预报。
  我们没有天气数据源，也不联网。早上刚开始记录时两个数字会比较接近，
  随着一天推移才逐渐拉开。

六、检查更新
  - 菜单栏图标 → 检查更新…（或 设置… → 软件更新 → 检查更新）
  - 会去开发服务器拉版本信息，有新版本会弹窗问你，还会显示更新说明
  - 点「下载并安装」后自动下载、校验、替换，然后自己重启，不用手动拖
  - 走的是 http，所以下载完会强制校验 sha256；对不上直接中止，
    不会解压也不会替换
  - 装的位置不在「应用程序」里的话（比如自己编译跑的），
    会改成把新版本解压出来给你，不自动替换

七、数据在哪
  ~/Library/Application Support/TempBar/state.json
  保留最近 7 天，删掉这个文件就清空历史（改的名字也会一起清掉）

八、卸载
  退出 App，把 TempBar.app 从「应用程序」删掉即可。
  App 不装任何后台服务，也不开机自启（除非你在设置里打开）。
TXT

echo "==> 校验"
unzip -t "$DIST/TempBar.zip" > /dev/null && echo "压缩包完整性 OK"
codesign -v "$APP" && echo "签名 OK"

echo ""
echo "产物："
ls -lh "$DIST"
echo ""
echo "把 dist/ 里的这两个文件发给同事即可。"
